/** 가나 한 글자. h=히라가나, k=가타카나, r=로마자, ko=한글음 */
data class Kana(val h:String, val k:String, val r:String, val ko:String){
    fun glyph(script:Script) = if(script==Script.HIRA) h else k

    /**
     * 학습 기록의 열쇠. 히라가나와 가타카나는 따로 익히는 글자라 기록도 따로 센다.
     * 히라가나 쪽은 접두사 없이 두어서 예전에 저장된 기록을 그대로 이어 쓴다.
     */
    fun id(script:Script) = if(script==Script.HIRA) h else "K$h"
}
enum class Script(val label:String){ HIRA("히라가나"), KATA("가타카나") }

