package com.nihongo.masu.data

/**
 * 문장 맞추기 — 예문에서 표제어를 가리고 그 자리에 들어갈 단어를 고르는 판.
 *
 * 안드로이드 API를 쓰지 않는 순수 함수라 [Srs]와 같은 자리에 둔다. 화면에 두면
 * 컴포즈 파일이 되어 JVM 단위 테스트에서 부를 수 없다.
 *
 * 학습 기록을 읽지도 쓰지도 않는다. 사지선다는 보기에서 답을 역추적할 수 있어서,
 * 복습 일정에 흘리면 찍어서 맞힌 카드가 익힘으로 오른다. 스피드를 아예 다른
 * 메뉴로 뺀 것과 같은 이유다.
 */
object Cloze {

    /** 한 판의 장수. */
    const val ROUND = 20

    /**
     * 빈칸. 전각 밑줄 세 개로 고정이다.
     *
     * 표기 길이만큼 그리면 몇 글자인지가 힌트로 샌다. 전각을 쓰는 이유는 반각
     * `___`이 일본어 글자 사이에서 아래로 처져 칸으로 안 보이기 때문이다.
     *
     * 사이에 낱말 이음쇠(U+2060)를 끼운다. 일본어는 어디서나 줄이 바뀔 수 있어서
     * 그냥 두면 긴 문장에서 칸이 `＿＿`와 `＿`로 쪼개져 두 줄에 걸린다.
     */
    const val BLANK = "＿⁠＿⁠＿"

    /**
     * 그 등급에서 쓸 수 있는 단어.
     *
     * 표기가 예문에 **통째로** 든 것만 쓴다. [Word.stem]을 쓰면 5,429개 전부에서
     * 표제어를 찾을 수 있지만(`DataTest`가 그걸 보장한다) 어간은 마지막 글자를
     * 떼기 때문에, 어간만 가리면 남은 글자가 빈칸 밖으로 샌다 —
     * `友達` → `＿＿＿達と映画を見ます`. 등급마다 500장이 넘어 활용형 400여 개를
     * 빼도 한 판([ROUND]장)에는 넘친다.
     *
     * [enough]와 [readable]까지 요구하는 이유는 아래를 보라 — 앞의 것은 빈칸
     * 밖에 문장이 남게, 뒤의 것은 「읽기 보기」가 정답을 흘리지 않게 한다.
     */
    fun pool(level: Level): List<Word> = pools[level].orEmpty()

    /**
     * 한 번만 걸러 둔다. 홈 타일이 [total]을 읽느라 켜자마자 통이 만들어지므로
     * 이 걸러내기가 첫 화면에 얹힌다 — 5,429줄을 등급마다 한 번씩 다섯 번 훑지 않고
     * 한 번 훑어 등급으로 묶는다.
     */
    private val pools: Map<Level, List<Word>> by lazy {
        VocabData.all
            .filter { it.w in it.ex && enough(it) && readable(it) }
            .groupBy { it.level }
    }

    /**
     * 빈칸을 파고도 문장이 남는 단어인가.
     *
     * 인사말은 예문이 그 인사말 하나로 되어 있어 가리면 문제가 사라진다 —
     * `いらっしゃいませ。` → `＿＿＿ませ。`, `先生、さようなら。` → `先生、＿＿＿。`.
     * 같은 분류에서 뽑은 넷 중 어느 것이 들어갈지 가릴 근거가 문장에 없다.
     * 표기 뺀 나머지 다섯 자를 요구하면 이런 13개가 빠지고, `私は学生です。`처럼
     * 조사와 서술어가 남아 자리를 정해 주는 문장은 남는다.
     *
     * 길이로만 재는 것이라 표기가 더 긴 낱말 안에 든 경우는 못 걸러낸다 —
     * `肩`의 예문 `今肩慣らししているところです。`는 `今＿＿＿慣らし…`가 되어
     * 빈칸이 `肩慣らし`를 가른다. 그걸 잡으려면 문장을 낱말로 끊어 봐야 하는데,
     * `tokens.tsv`를 통 만드는 데까지 끌어들일 값어치는 아직 없다.
     */
    private fun enough(w: Word): Boolean = w.ex.length - w.w.length >= 5

    /**
     * 예문 읽기에서도 표제어를 가릴 수 있는 단어인가.
     *
     * 나오는 횟수까지 같아야 한다. 읽기가 짧으면 문장 다른 데서 또 걸려서, 다
     * 가리면 엉뚱한 자리가 뚫린다 — `木`(き)의 예문 읽기
     * `こうえんにおおきいきがあります`를 `き`로 가리면 `おお＿＿＿い＿＿＿`가 된다.
     * 이 조건에 걸려 빠지는 것은 78개뿐이다.
     */
    private fun readable(w: Word): Boolean =
        w.read in w.exRead && w.exRead.occurrences(w.read) == w.ex.occurrences(w.w)

    /** 겹치지 않게 센 [sub]의 개수. */
    private fun String.occurrences(sub: String): Int = split(sub).size - 1

    /**
     * 예문에서 표기를 [BLANK]로 갈아 낀다.
     *
     * 표기가 예문에 두 번 나오는 단어 26개(`歌`·`北`·`千`·`日`·`百` 등)는 두
     * 자리가 다 가려진다. 한 자리만 남기면 남은 쪽이 그대로 정답이 된다.
     */
    fun blank(w: Word): String = w.ex.replace(w.w, BLANK)

    /**
     * 예문 읽기에서 표제어의 읽기를 [BLANK]로 갈아 낀다.
     *
     * 막혔을 때 여는 문이다. 한자가 안 읽혀서 문장을 못 읽는 것과 답을 모르는 것은
     * 다른 문제인데, 앞의 것 때문에 막힌 사람에게 뜻을 보여주면 답까지 준다 —
     * `＿＿＿と映画を見ます`의 뜻 「친구와 영화를 봅니다」는 그대로 정답이다.
     * 읽기는 나머지 글자만 풀어 주고 빈칸은 빈칸으로 남긴다.
     */
    fun blankRead(w: Word): String = w.exRead.replace(w.read, BLANK)

    /**
     * 보이는 글자 수. 글자 크기를 정할 때 쓴다.
     *
     * [BLANK]에 낀 낱말 이음쇠는 폭을 안 차지하는데 [String.length]는 센다.
     * 그냥 세면 빈칸 수만큼 길이가 부풀어, 같은 폭으로 그려질 두 문장이
     * 정답 길이에 따라 서로 다른 크기로 나온다.
     */
    fun glyphs(s: String): Int = s.count { it != '\u2060' }

    /** 다섯 등급을 통틀어 쓸 수 있는 단어 수. 홈 타일이 통 크기를 적는다. */
    val total: Int by lazy { pools.values.sumOf { it.size } }
}
